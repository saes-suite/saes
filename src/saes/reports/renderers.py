def _import_matplotlib_pyplot() -> Any:
    """Import Matplotlib safely, raising an informative ConfigurationError if `[viz]` extra is missing."""
    try:
        import matplotlib

        matplotlib.use("Agg")
        import matplotlib.pyplot as plt

        return plt
    except ImportError as exc:
        raise ConfigurationError(
            "PDF table export requires Matplotlib. Install visualization extras with: pip install 'saes[viz]'"
        ) from exc


def _build_pdf_bytes(
    result: StatisticalTableResult,
    title: str | None = None,
    caption: str | None = None,
    theme: str = "slate",
    orientation: str = "landscape",
    font_size: float = 8.5,
    highlight_best: bool = True,
    show_zebra: bool = True,
    grid_style: str = "full",
) -> bytes:
    """Render a publication-grade vector PDF table using Matplotlib PDF backend."""
    plt = _import_matplotlib_pyplot()
    headers, rows, bolds = _extract_flat_headers_and_rows(result)
    n_rows = len(rows)
    n_cols = max(1, len(headers))

    palette = PDF_THEMES.get((theme or "").lower().strip(), PDF_THEMES["slate"])
    is_portrait = (orientation or "").lower().strip() == "portrait"
    if is_portrait:
        fig_w = max(8.5, min(16.0, 1.8 * n_cols))
        fig_h = max(11.0, min(32.0, 2.0 + 0.42 * (n_rows + 2)))
    else:
        fig_w = max(11.0, min(24.0, 2.2 * n_cols))
        fig_h = max(5.0, min(24.0, 1.8 + 0.42 * (n_rows + 2)))

    fig, ax = plt.subplots(figsize=(fig_w, fig_h))
    ax.axis("off")

    title_str = (
        title.strip()
        if title and title.strip()
        else f"SAES Statistical Benchmark Table — Metric: {result.metric} (α = {result.alpha})"
    )
    caption_str = caption.strip() if caption and caption.strip() else result.caption

    ax.set_title(
        title_str,
        fontsize=max(10.0, font_size + 3.0),
        fontweight="bold",
        loc="left",
        pad=14,
        color=palette["title_color"],
    )

    tbl = ax.table(cellText=rows, colLabels=headers, loc="center", cellLoc="center")
    tbl.auto_set_font_size(False)
    tbl.set_fontsize(font_size)
    tbl.scale(1.0, 1.35 if font_size < 8.0 else (1.45 if font_size < 10.0 else 1.6))

    border_color = palette["border"]
    clean_grid = (grid_style or "").lower().strip()

    for (r_idx, c_idx), cell in tbl.get_celld().items():
        cell.set_linewidth(0.6)
        if clean_grid == "horizontal":
            cell.set_edgecolor(border_color)
            cell.visible_edges = "TB"
        elif clean_grid == "minimal":
            if r_idx == 0:
                cell.visible_edges = "TB"
                cell.set_linewidth(1.2)
            elif r_idx == n_rows:
                cell.visible_edges = "B"
                cell.set_linewidth(1.2)
            else:
                cell.visible_edges = ""
            cell.set_edgecolor(border_color)
        else:
            cell.set_edgecolor(border_color)

        if r_idx == 0:
            cell.set_facecolor(palette["header_bg"])
            cell.set_text_props(color=palette["header_fg"], weight="bold")
        else:
            data_r = r_idx - 1
            is_b = bolds[data_r][c_idx] if (data_r < len(bolds) and c_idx < len(bolds[data_r])) else False
            is_footer = result.table_type == "instance_algorithm" and data_r >= len(result.instance_rows)
            if is_footer:
                cell.set_facecolor(palette["footer_bg"])
                cell.set_text_props(weight="bold", color=palette["footer_fg"])
            elif is_b and highlight_best:
                cell.set_facecolor(palette["best_bg"])
                cell.set_text_props(weight="bold", color=palette["best_fg"])
            else:
                bg = palette["zebra_odd"] if (show_zebra and data_r % 2 != 0) else palette["zebra_even"]
                cell.set_facecolor(bg)
                cell.set_text_props(color=palette["text"])

    fig.text(
        0.02,
        0.02,
        caption_str,
        fontsize=max(7.0, font_size - 1.0),
        color=palette["caption_color"],
        style="italic",
        wrap=True,
    )
    buf = io.BytesIO()
    fig.savefig(buf, format="pdf", bbox_inches="tight", dpi=300)
    plt.close(fig)
    return buf.getvalue()


class TableRenderer(ABC):
    """Abstract base class for extensible `StatisticalTableResult` format renderers."""

    @property
    @abstractmethod
    def media_type(self) -> str:
        """MIME type for the rendered artifact."""

    @property
    @abstractmethod
    def extension(self) -> str:
        """File extension without leading dot."""

    @abstractmethod
    def render(self, result: StatisticalTableResult, **kwargs: Any) -> bytes:
        """Render `StatisticalTableResult` to bytes."""


class LaTeXTableRenderer(TableRenderer):
    media_type = "application/x-tex"
    extension = "tex"

    def render(self, result: StatisticalTableResult, **kwargs: Any) -> bytes:
        doc_mode = kwargs.get("document_mode") or getattr(result, "latex_document_mode", "standalone") or "standalone"
        not_mode = kwargs.get("notation") or getattr(result, "latex_notation", "scientific") or "scientific"
        precision = int(kwargs.get("precision", 4))
        return render_latex_table(result, precision=precision, document_mode=doc_mode, notation=not_mode).encode(
            "utf-8"
        )


class MarkdownTableRenderer(TableRenderer):
    media_type = "text/markdown"
    extension = "md"

    def render(self, result: StatisticalTableResult, **kwargs: Any) -> bytes:
        _ = kwargs
        md = result.markdown_preview or render_markdown_table(result)
        return md.encode("utf-8")


class CSVTableRenderer(TableRenderer):
    media_type = "text/csv"
    extension = "csv"

    def render(self, result: StatisticalTableResult, **kwargs: Any) -> bytes:
        _ = kwargs
        headers, rows, _ = _extract_flat_headers_and_rows(result)
        out = io.StringIO()
        pd.DataFrame(rows, columns=headers).to_csv(out, index=False)
        return out.getvalue().encode("utf-8")


