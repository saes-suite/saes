"""Extensible publication-grade table renderers and multi-format exporters (LaTeX, Markdown, CSV, HTML, DOCX, PDF).

Architecture inspired by Leifeld (2013, JSS v55i08 `texreg`): separates statistical table
computation (`saes.stats.tables`) from presentation rendering via `TableRenderer` and
`TableRendererRegistry`, enabling users to register custom output formats cleanly.
"""

